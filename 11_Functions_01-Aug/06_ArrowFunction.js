const myfruits = (fruits) => `My favourite fruit is ${fruits}`;

console.log(myfruits("Mango")); // Output: My favourite fruit is Mango

// after const , mention the name of the function
// in this case it is myfruits
// after = mention the parameter of the function in this case it is fruits
// after => mention the return value of the function in this case it is `My favourite fruit is ${fruits}`

const doublescore =(score) => score*score;

console.log(doublescore(5)); // Output: 25


